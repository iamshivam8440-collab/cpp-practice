// Print example of int,float,double,char,and bool;
#include <iostream>
using namespace std;
int main()
{
    int a = 20;
    float b = 2.5;
    double c = 2.4;
    char d = 'N';
    bool e = true;
    cout << "Data types and their value:" << endl;
    cout << "int = " << a << endl;
    cout << "float = " << b << endl;
    cout << "double = " << c << endl;
    cout << "char = " << d << endl;
    cout << "bool = " << e << endl;
    return 0;
}